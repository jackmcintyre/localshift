def _slot(index: int, price: float, *, clock_dw: bool = False) -> SlotContext:
    return SlotContext(
        slot_index=index,
        timestamp_iso=f"2026-09-07T{9 + index // 2:02d}:{30 * (index % 2):02d}:00+10:00",
        slot_interval_minutes=30,
        buy_price=price,
        sell_price=0.0,
        solar_kwh=0.0,
        consumption_kwh=1.0,
        is_demand_window_slot=clock_dw,
        is_demand_window_entry=False,
    )


def _day(prices: list[float], clock_dw: tuple[int, ...] = ()) -> list[SlotContext]:
    slots = [_slot(i, p, clock_dw=i in clock_dw) for i, p in enumerate(prices)]
    if clock_dw:
        slots[clock_dw[0]].is_demand_window_entry = True
    return slots


def _flags(slots: list[SlotContext]) -> str:
    return "".join(
        "E" if s.is_demand_window_entry else "D" if s.is_demand_window_slot else "."
        for s in slots
    )


_ON = OptimizerConfig(price_block_target=True)
# Cheap morning, then a five-slot dear evening from index 4.
_PRICES = [0.07, 0.07, 0.07, 0.07, 0.19, 0.19, 0.19, 0.19, 0.19, 0.07]


def test_switch_off_leaves_slots_and_state_alone() -> None:
    slots = _day(_PRICES, clock_dw=(2, 3))
    data = CoordinatorData()
    data.target_block_entry_idx = 7
    data.target_block_entry_iso = "stale"

    block = apply_price_block_flags(slots, OptimizerConfig(), data)

    assert block is None
    assert _flags(slots) == "..ED......"
    assert data.target_block_entry_idx is None
    assert data.target_block_entry_iso is None


def test_block_overwrites_the_clock_window() -> None:
    slots = _day(_PRICES, clock_dw=(1, 2, 3, 4, 5))
    data = CoordinatorData()

    block = apply_price_block_flags(slots, _ON, data)

    assert block is not None
    assert (block.entry_idx, block.end_idx) == (4, 8)
    assert _flags(slots) == "....EDDDD."
    assert data.target_block_entry_idx == 4
    assert data.target_block_entry_iso == slots[4].timestamp_iso


def test_no_block_clears_every_flag_and_the_stored_entry() -> None:
    slots = _day([0.15] * 10, clock_dw=(4, 5, 6))
    data = CoordinatorData()
    data.target_block_entry_idx = 4
    data.target_block_entry_iso = slots[4].timestamp_iso

    block = apply_price_block_flags(slots, _ON, data)

    assert block is None
    assert _flags(slots) == "." * 10
    assert data.target_block_entry_idx is None
    assert data.target_block_entry_iso is None


def test_previous_entry_is_matched_by_time_not_by_index() -> None:
    """The horizon slides between plans, so a stored index means a later slot.

    The previous plan entered at 11:30. Half an hour on, the same 11:30 slot is
    one index earlier. Matching by index would see 5 against a fresh 4 and hold
    the entry one slot late on every re-plan; matching by time sees no change.
    """
    earlier = _day([0.07, *_PRICES])
    data = CoordinatorData()
    apply_price_block_flags(earlier, _ON, data)
    assert data.target_block_entry_idx == 5
    entered_at = data.target_block_entry_iso

    later = _day(_PRICES)
    for slot in later:
        slot.timestamp_iso = earlier[slot.slot_index + 1].timestamp_iso
    block = apply_price_block_flags(later, _ON, data)

    assert block is not None
    assert block.entry_idx == 4
    assert later[4].timestamp_iso == entered_at
    assert "held" not in block.reason


def test_previous_entry_one_slot_away_is_held() -> None:
    slots = _day(_PRICES)
    data = CoordinatorData()
    data.target_block_entry_iso = slots[5].timestamp_iso

    block = apply_price_block_flags(slots, _ON, data)

    assert block is not None
    assert block.entry_idx == 5
    assert _flags(slots) == ".....EDDD."
    assert data.target_block_entry_idx == 5


def test_previous_entry_two_slots_away_is_not_held() -> None:
    slots = _day(_PRICES)
    data = CoordinatorData()
    data.target_block_entry_iso = slots[6].timestamp_iso

    block = apply_price_block_flags(slots, _ON, data)

    assert block is not None
    assert block.entry_idx == 4


