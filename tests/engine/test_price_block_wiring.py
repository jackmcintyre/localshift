"""Price block wired into the planner's slot flags (docs/PRICE_BLOCK_TARGET.md; #1107).

With ``switch.localshift_price_block_target`` ON the detected block replaces the
clock demand window as the thing that sets ``is_demand_window_slot`` and
``is_demand_window_entry``. Everything downstream (terminal penalty, hard floor,
water level, urgency window, import ban) reads those two flags and follows.

The non-negotiable property is the first test: with the switch OFF the flags the
planner sees and the plan it produces are identical to the code before this
change. ``price_block_switch_off_golden.json`` was captured from commit 83badbb,
the parent of the wiring commit, by the driver's ``capture_all()``, and is never
regenerated by the test run.

Scenarios are driven by ``tests/helpers/price_block_driver.py`` the way
``scripts/replay_no_dw.py`` ``run_arm`` drives them: ``forecast_horizon_hours``
seeded before the first pass, two passes, the second reported (#1053).
"""

