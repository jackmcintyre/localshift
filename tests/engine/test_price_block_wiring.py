@pytest.fixture(scope="module")
def on_0907() -> Run:
    return drive(load(CAPTURE_0907), price_block_target=True, live=True)


def test_0907_block_replaces_the_clock_window_flags(on_0907: Run) -> None:
    slots = on_0907.slots
    flagged = [s for s in slots if s.is_demand_window_slot]
    entries = [s for s in slots if s.is_demand_window_entry]

    assert len(entries) == 1
    assert _local(entries[0].timestamp_iso) == "16:30"
    assert flagged[0] is entries[0]
    assert _local(flagged[-1].timestamp_iso) == "00:00"
    # Contiguous: the block, the whole block and nothing but the block.
    assert [s.slot_index for s in flagged] == list(
        range(flagged[0].slot_index, flagged[-1].slot_index + 1)
    )
    # The clock window's 15:00-16:00 slots are not in it.
    early = [s for s in slots if _local(s.timestamp_iso) in ("15:00", "15:30", "16:00")]
    assert early
    assert not any(s.is_demand_window_slot for s in early)


def test_0907_plan_grid_charges_before_block_entry(on_0907: Run) -> None:
    entry = next(s for s in on_0907.slots if s.is_demand_window_entry)
    entry_at = datetime.fromisoformat(entry.timestamp_iso)
    charges = on_0907.charge_times()

    assert charges, "the block funded no pre-charge"
    assert any(t < entry_at for t in charges)


def test_0907_plan_schedules_no_grid_charge_after_2100(on_0907: Run) -> None:
    first = datetime.fromisoformat(on_0907.decisions[0]["timestamp_iso"])
    nine_pm = first.replace(hour=21, minute=0, second=0, microsecond=0)

    late = [t for t in on_0907.charge_times() if t >= nine_pm]
    assert late == []


def test_0907_entry_is_persisted_for_hysteresis(on_0907: Run) -> None:
    entry = next(s for s in on_0907.slots if s.is_demand_window_entry)

    assert on_0907.data.target_block_entry_idx == entry.slot_index
    assert on_0907.data.target_block_entry_iso == entry.timestamp_iso


def test_0907_held_entry_survives_the_engine(on_0907: Run) -> None:
    """A previous plan one slot later than the fresh detection holds the entry."""
    entry = next(s for s in on_0907.slots if s.is_demand_window_entry)
    later = on_0907.slots[entry.slot_index + 1]

    held = drive(
        load(CAPTURE_0907),
        price_block_target=True,
        live=True,
        previous_entry_iso=later.timestamp_iso,
    )

    held_entry = next(s for s in held.slots if s.is_demand_window_entry)
    assert held_entry.timestamp_iso == later.timestamp_iso
    assert held.data.target_block_entry_idx == later.slot_index


