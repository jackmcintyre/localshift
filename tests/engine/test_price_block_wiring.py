def _local(stamp: str) -> str:
    return datetime.fromisoformat(stamp).strftime("%H:%M")


def _outcome(run: Run) -> dict[str, Any]:
    return {k: v for k, v in run.result.items() if k != "states_explored"}


def _flat(scenario: dict[str, Any], price: float = 0.15) -> dict[str, Any]:
    """The same day with every buy price flattened: nothing is dearer than anything."""
    flat = copy.deepcopy(scenario)
    for row in flat["input"]["general_forecast"]:
        for key in ("per_kwh", "price", "advanced_price_predicted", "spot_per_kwh"):
            if key in row:
                row[key] = price
    flat["input"]["general_price"] = price
    return flat


