def _slot(index: int, price: float, load_kwh: float) -> SlotContext:
    return SlotContext(
        slot_index=index,
        timestamp_iso=f"2026-09-07T{9 + index // 2:02d}:{30 * (index % 2):02d}:00+10:00",
        slot_interval_minutes=30,
        buy_price=price,
        sell_price=0.0,
        solar_kwh=0.0,
        consumption_kwh=load_kwh,
        is_demand_window_slot=False,
        is_demand_window_entry=False,
    )


# Cheap morning, then a five-slot dear evening from index 4.
_PRICES = [0.07, 0.07, 0.07, 0.07, 0.19, 0.19, 0.19, 0.19, 0.19, 0.07]
_OPTIONS = {CONF_BATTERY_TARGET: 95, CONF_MINIMUM_TARGET_SOC: 20}


def _day(load_kwh: float, prices: list[float] | None = None) -> list[SlotContext]:
    return [_slot(i, p, load_kwh) for i, p in enumerate(prices or _PRICES)]


def _config(**kwargs: Any) -> OptimizerConfig:
    return OptimizerConfig(
        battery_capacity_kwh=13.5,
        discharge_efficiency=0.95,
        min_soc_pct=20.0,
        demand_window_target_soc_pct=95.0,
        **kwargs,
    )


def test_switch_off_leaves_the_target_alone() -> None:
    config = _config(price_block_target=False)
    slots = _day(1.0)

    block = apply_price_block(slots, config, _OPTIONS, CoordinatorData())

    assert block is None
    assert config.demand_window_target_soc_pct == 95.0
    assert not any(s.is_demand_window_slot for s in slots)


def test_switch_on_sizes_the_target_to_the_block() -> None:
    config = _config(price_block_target=True)
    slots = _day(0.5)

    block = apply_price_block(slots, config, _OPTIONS, CoordinatorData())

    assert block is not None
    # Five slots of 0.5 kWh through a 95% discharge, of a 13.5 kWh battery.
    needed_pct = 5 * 0.5 / 0.95 / 13.5 * 100.0
    assert block.needed_pct == pytest.approx(needed_pct)
    assert config.demand_window_target_soc_pct == pytest.approx(20.0 + needed_pct)
    assert slots[4].is_demand_window_entry


def test_switch_on_adds_the_adaptive_headroom() -> None:
    config = _config(price_block_target=True)
    data = CoordinatorData()
    data.adaptive_params = {
        "grid_charge_soc_headroom": 2.0,
        "overnight_drain_safety_margin": 1.5,
    }

    block = apply_price_block(_day(0.5), config, _OPTIONS, data)

    assert block is not None
    assert config.demand_window_target_soc_pct == pytest.approx(
        20.0 + block.needed_pct + 3.5
    )


def test_switch_on_inflated_load_is_capped_at_battery_target() -> None:
    config = _config(price_block_target=True)

    block = apply_price_block(_day(6.0), config, _OPTIONS, CoordinatorData())

    assert block is not None
    assert block.needed_pct > 100.0
    assert config.demand_window_target_soc_pct == 95.0


def test_switch_on_without_a_block_targets_the_minimum() -> None:
    config = _config(price_block_target=True)
    slots = _day(1.0, prices=[0.15] * 10)

    block = apply_price_block(slots, config, _OPTIONS, CoordinatorData())

    assert block is None
    assert config.demand_window_target_soc_pct == 20.0


def test_switch_on_missing_options_fall_back_to_the_defaults() -> None:
    config = _config(price_block_target=True)

    block = apply_price_block(_day(6.0), config, {}, CoordinatorData())

    assert block is not None
    assert config.demand_window_target_soc_pct == float(DEFAULT_BATTERY_TARGET)


def test_persist_false_still_sizes_the_target() -> None:
    """The shadow plan is sized to its own block without moving the live entry."""
    config = _config(price_block_target=True)
    data = CoordinatorData()

    block = apply_price_block(_day(0.5), config, _OPTIONS, data, persist=False)

    assert block is not None
    assert config.demand_window_target_soc_pct == pytest.approx(20.0 + block.needed_pct)
    assert data.target_block_entry_iso is None


