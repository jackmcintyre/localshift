"""Load-sized target SOC for a price-only block (docs/PRICE_BLOCK_TARGET.md; #1108).

A price-only block charges to what the evening needs, not to ``battery_target``:

    clamp(minimum_target_soc + needed_pct + headroom,
          minimum_target_soc, battery_target)

With ``switch.localshift_price_block_target`` ON and no block the target is
``minimum_target_soc``, so the terminal machinery has nothing to enforce. With
the switch OFF the target is what it was before this change:
``price_block_switch_off_target_golden.json`` was captured from commit 96f75af,
the parent of this change, by the driver's ``capture_targets()``, and is never
regenerated by the test run.
"""

