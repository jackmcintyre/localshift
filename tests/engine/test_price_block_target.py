def test_block_target_is_minimum_plus_need() -> None:
    assert price_block_target_soc(
        _block(30.0), minimum_target_soc=20.0, battery_target=95.0
    ) == pytest.approx(50.0)


def test_existing_headroom_is_added_to_the_need() -> None:
    assert price_block_target_soc(
        _block(30.0), minimum_target_soc=20.0, battery_target=95.0, headroom_pct=3.5
    ) == pytest.approx(53.5)


def test_need_beyond_one_battery_is_pinned_at_battery_target() -> None:
    # The real 2026-09-07 block needs about 220% of the battery.
    assert (
        price_block_target_soc(
            _block(220.0), minimum_target_soc=5.0, battery_target=95.0
        )
        == 95.0
    )


def test_headroom_cannot_lift_the_target_past_battery_target() -> None:
    assert (
        price_block_target_soc(
            _block(74.0), minimum_target_soc=20.0, battery_target=95.0, headroom_pct=5.0
        )
        == 95.0
    )


def test_no_block_targets_the_minimum() -> None:
    assert (
        price_block_target_soc(None, minimum_target_soc=20.0, battery_target=95.0)
        == 20.0
    )


def test_no_block_ignores_headroom() -> None:
    assert (
        price_block_target_soc(
            None, minimum_target_soc=20.0, battery_target=95.0, headroom_pct=5.0
        )
        == 20.0
    )


def test_block_needing_nothing_targets_the_minimum() -> None:
    assert (
        price_block_target_soc(_block(0.0), minimum_target_soc=20.0, battery_target=95)
        == 20.0
    )


def test_negative_headroom_cannot_pull_the_target_below_the_minimum() -> None:
    assert (
        price_block_target_soc(
            _block(2.0), minimum_target_soc=20.0, battery_target=95.0, headroom_pct=-9.0
        )
        == 20.0
    )


@pytest.mark.parametrize("needed", [float("nan"), float("inf"), float("-inf")])
def test_unusable_need_never_escapes_the_bounds(needed: float) -> None:
    target = price_block_target_soc(
        _block(needed), minimum_target_soc=20.0, battery_target=95.0
    )
    assert 20.0 <= target <= 95.0


def test_minimum_above_battery_target_yields_battery_target() -> None:
    """A misconfiguration: the ceiling wins, the target never exceeds it."""
    for block in (None, _block(30.0)):
        assert (
            price_block_target_soc(block, minimum_target_soc=90.0, battery_target=60.0)
            == 60.0
        )


@pytest.mark.parametrize("needed", [0.0, 0.4, 12.0, 74.9, 75.0, 75.1, 220.0, 1e6])
@pytest.mark.parametrize("headroom", [0.0, 2.0, 10.0])
def test_target_always_inside_the_bounds(needed: float, headroom: float) -> None:
    target = price_block_target_soc(
        _block(needed),
        minimum_target_soc=20.0,
        battery_target=95.0,
        headroom_pct=headroom,
    )
    assert 20.0 <= target <= 95.0


