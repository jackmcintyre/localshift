LIVE_MINIMUM = float(LIVE_OVERRIDES["minimum_target_soc"])
LIVE_TARGET = float(LIVE_OVERRIDES["battery_target"])


def _block(needed_pct: float) -> TargetBlock:
    return TargetBlock(
        entry_idx=4,
        end_idx=8,
        needed_kwh=needed_pct / 100.0 * 13.5,
        needed_pct=needed_pct,
        reason="test",
    )


